// Generates tianxi/web/light.css: the light theme, derived from style.css by flipping every neutral grey
// (backgrounds, borders, text) while keeping real colors. Re-run after changing style.css:
//   node build/tools/gen-light.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const css = fs.readFileSync(path.join(ROOT, 'tianxi/web/style.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')
const P = ':where(:root[data-theme=light])'

const hex = (h) => { h = h.slice(1); if (h.length === 3) h = [...h].map((c) => c + c).join(''); return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)) }
const toHex = (rgb) => '#' + rgb.map((v) => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, '0')).join('')
const neutral = ([r, g, b]) => Math.max(r, g, b) - Math.min(r, g, b) < 14
// Dark surfaces become near-white ones (slightly cool, like the reference), light text becomes ink.
function flip(rgb, prop) {
  const l = (rgb[0] + rgb[1] + rgb[2]) / 3
  const g = (v, b = 6) => [v, v, v + b > 255 ? 255 : v + b]
  if (/border|outline|stroke/.test(prop)) return l < 50 ? g(226, 8) : l < 120 ? g(206, 8) : g(40, 6)
  if (/background|fill|box-shadow/.test(prop)) {
    // dark: deepest = page, a step up = cards. light: page is a soft grey, cards are white.
    if (l < 22) return g(243, 6)
    if (l < 37) return [255, 255, 255]
    if (l < 50) return g(236, 6)
    if (l < 64) return g(226, 8)
    if (l < 100) return g(212, 8)
    if (l > 200) return g(28 + (255 - l) * 0.3, 6)
    return g(255 - l + 30, 8)
  }
  // text: light ink becomes dark ink, keeping its rank
  if (l > 150) return g(22 + (255 - l) * 0.9, 6)
  if (l < 60) return [250, 250, 252]
  return g(Math.min(140, 255 - l), 8)
}
function mapValue(v, prop) {
  let out = v.replace(/#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b/g, (m) => { const c = hex(m); return neutral(c) ? toHex(flip(c, prop)) : m })
  out = out.replace(/rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+))?\s*\)/g, (m, r, g, b, a) => {
    const c = [+r, +g, +b]; if (!neutral(c)) return m
    const l = (c[0] + c[1] + c[2]) / 3
    if (a !== undefined) return l > 128 ? `rgba(20,20,40,${(+a * 0.9).toFixed(3)})` : `rgba(80,70,120,${(+a * 0.35).toFixed(3)})`
    return toHex(flip(c, prop))
  })
  return out
}
// tiny parser: top-level rules and @media blocks; keyframes are left alone
function rules(src) {
  const out = []; let i = 0
  while (i < src.length) {
    const open = src.indexOf('{', i); if (open < 0) break
    const sel = src.slice(i, open).trim()
    let depth = 1, j = open + 1
    while (j < src.length && depth) { if (src[j] === '{') depth++; else if (src[j] === '}') depth--; j++ }
    const body = src.slice(open + 1, j - 1)
    if (sel.startsWith('@media')) out.push({ media: sel, rules: rules(body) })
    else if (!sel.startsWith('@')) out.push({ sel, body })
    i = j
  }
  return out
}
function emit(list) {
  let s = ''
  for (const r of list) {
    if (r.media) { const inner = emit(r.rules); if (inner) s += `${r.media}{\n${inner}}\n`; continue }
    const decls = []
    for (const d of r.body.split(';')) {
      const k = d.indexOf(':'); if (k < 0) continue
      const prop = d.slice(0, k).trim(), val = d.slice(k + 1).trim()
      if (!/#|rgb/.test(val) || prop.startsWith('--ease')) continue
      const nv = mapValue(val, prop.startsWith('--') ? (/^--(tx|link)/.test(prop) ? 'color' : /^--line/.test(prop) ? 'border' : 'background') : prop)
      if (nv !== val) decls.push(`${prop}:${nv}`)
    }
    if (!decls.length) continue
    const sel = r.sel.split(',').map((x) => x.trim()).map((x) => /^(:root|html)\b/.test(x) ? ':root[data-theme=light]' + x.replace(/^(:root|html)/, '') : x.startsWith('body') ? P + ' ' + x : P + ' ' + x).join(',')
    s += `${sel}{${decls.join(';')}}\n`
  }
  return s
}
const head = `/* Generated by build/tools/gen-light.mjs from style.css — do not edit by hand; edit light-extra.css. */\n${P}{color-scheme:light}\n`
fs.writeFileSync(path.join(ROOT, 'tianxi/web/light.css'), head + emit(rules(css)))
console.log('light.css written')
